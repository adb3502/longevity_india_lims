-- Create views for easy querying
CREATE OR REPLACE VIEW v_bharat_enrollment_summary AS
SELECT 
  CENTER_CODE,
  AGE_GROUP,
  SUM(CASE WHEN GENDER = 'A' THEN CURRENT_COUNT ELSE 0 END) as MALE_COUNT,
  SUM(CASE WHEN GENDER = 'B' THEN CURRENT_COUNT ELSE 0 END) as FEMALE_COUNT,
  SUM(CURRENT_COUNT) as TOTAL_COUNT,
  SUM(TARGET_COUNT) as TOTAL_TARGET,
  ROUND(SUM(CURRENT_COUNT) * 100.0 / SUM(TARGET_COUNT), 2) as COMPLETION_PERCENTAGE
FROM os_bharat_enrollment_stats
GROUP BY CENTER_CODE, AGE_GROUP;

CREATE OR REPLACE VIEW v_bharat_participant_details AS
SELECT 
  p.IDENTIFIER as PARTICIPANT_ID,
  bp.FULL_CODE,
  bp.CENTER_CODE,
  bp.AGE_GROUP,
  bp.GENDER,
  bp.ENROLLMENT_DATE,
  p.FIRST_NAME,
  p.LAST_NAME,
  p.BIRTH_DATE,
  p.VITAL_STATUS,
  COUNT(DISTINCT s.IDENTIFIER) as SAMPLE_COUNT
FROM CATISSUE_PARTICIPANT p
JOIN os_bharat_participants bp ON p.IDENTIFIER = bp.PARTICIPANT_ID
LEFT JOIN CATISSUE_SPECIMEN s ON p.IDENTIFIER = s.SPECIMEN_COLLECTION_GROUP_ID
GROUP BY p.IDENTIFIER;